# Aggregate cells -> pseudo-metacells
# =============================================================================

def aggregate_counts_to_metacells(
    counts_gene_by_cell: sparse.csr_matrix,
    cell_library_size: np.ndarray,
    metacell_labels: pd.Series,
    scale_factor: float,
) -> Tuple[pd.DataFrame, pd.DataFrame, np.ndarray]:
    labels = metacell_labels.to_numpy(dtype=int)
    n_cells = len(labels)
    n_meta = int(labels.max()) + 1

    membership = sparse.csr_matrix(
        (
            np.ones(n_cells, dtype=np.float32),
            (np.arange(n_cells), labels),
        ),
        shape=(n_cells, n_meta),
    )

    meta_counts = (counts_gene_by_cell @ membership).tocsr()
    meta_lib = np.asarray(membership.T.dot(cell_library_size)).reshape(-1)

    if (meta_lib <= 0).any():
        bad = np.where(meta_lib <= 0)[0].tolist()
        raise ValueError(f"Pseudo-metacells with zero library size: {bad[:20]}")

    scale = float(scale_factor) / meta_lib
    norm_mat = meta_counts @ sparse.diags(scale.astype(np.float64))
    norm_mat = norm_mat.tocsr().astype(np.float64)
    norm_mat.data = np.log1p(norm_mat.data)

    raw_dense = meta_counts.toarray().T  # meta x genes
    log_dense = norm_mat.toarray().T     # meta x genes

    return (
        pd.DataFrame(raw_dense),
        pd.DataFrame(log_dense),
        meta_lib,
    )


