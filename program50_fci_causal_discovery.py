def read_names(path: str | Path) -> pd.Index:
    path = Path(path)
    x = pd.read_csv(path, sep="\t", header=None, dtype=str)
    return pd.Index(x.iloc[:, 0].astype(str).values)


def read_table_auto(path: str | Path, index_col=0) -> pd.DataFrame:
    path = str(path)
    df = pd.read_csv(path, sep="\t", index_col=index_col)
    if df.shape[1] <= 1:
        df = pd.read_csv(path, sep=",", index_col=index_col)
    df.index = df.index.astype(str)
    df.columns = df.columns.astype(str)
    return df


def ensure_exists(path: str | Path, label: str) -> Path:
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(f"{label} not found: {p}")
    return p


def sanitize_filename(x: object) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "_", str(x)).strip("_") or "program"


def resolve_program_name(query: object, labels: Sequence[str]) -> str:
    """
    Prefer exact match. Conservative fallback matches case-insensitively and
    numeric aliases such as Program69 <-> 69.
    """
    labels = [str(x) for x in labels]
    q = str(query)

    if q in labels:
        return q

    lower_map = defaultdict(list)
    for x in labels:
        lower_map[x.lower()].append(x)
    if q.lower() in lower_map and len(lower_map[q.lower()]) == 1:
        return lower_map[q.lower()][0]

    def key(x: str) -> str:
        z = x.strip().lower()
        z = re.sub(r"^program[\s_\-]*", "", z)
        z = re.sub(r"[^a-z0-9]+", "", z)
        return z

    qk = key(q)
    candidates = [x for x in labels if key(x) == qk]
    if len(candidates) == 1:
        return candidates[0]

    raise KeyError(
        f"Cannot uniquely resolve target_program={query!r}. "
        f"Examples of available programs: {labels[:20]}"
    )


