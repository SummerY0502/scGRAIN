def detect_metadata_cell_col(meta: pd.DataFrame, requested: str) -> str:
    if requested is not None and str(requested).lower() not in {"", "auto", "none", "null"}:
        if requested not in meta.columns:
            raise KeyError(
                f"metadata_cell_col={requested!r} not found. "
                f"Available columns: {list(meta.columns)}"
            )
        return str(requested)

    for c in ["cell", "barcode", "cell_id", "Cell", "Barcode", "Unnamed: 0"]:
        if c in meta.columns:
            return c
    return str(meta.columns[0])


def load_selected_metadata_cells() -> Tuple[pd.DataFrame, str]:
    meta = pd.read_csv(ensure_exists(CONFIG["metadata_file"], "metadata_file"))
    meta.columns = meta.columns.astype(str)

    cluster_col = str(CONFIG["metadata_cluster_col"])
    if cluster_col not in meta.columns:
        raise KeyError(
            f"metadata cluster column {cluster_col!r} not found. "
            f"Available: {list(meta.columns)}"
        )

    cell_col = detect_metadata_cell_col(meta, str(CONFIG["metadata_cell_col"]))
    meta[cell_col] = meta[cell_col].astype(str)

    keep = meta[cluster_col].astype(str).eq(str(CONFIG["metadata_cluster_name"]))
    meta = meta.loc[keep].copy()
    meta = meta.drop_duplicates(subset=[cell_col]).set_index(cell_col, drop=True)
    meta.index = meta.index.astype(str)

    if len(meta) == 0:
        raise ValueError(
            f"No cells with {cluster_col} == {CONFIG['metadata_cluster_name']!r}."
        )

    return meta, cell_col


def orient_usages_cell_by_program(
    usages: pd.DataFrame,
    known_cells: Sequence[str],
    program_names: Sequence[str],
) -> pd.DataFrame:
    usages = usages.copy()
    usages.index = usages.index.astype(str)
    usages.columns = usages.columns.astype(str)

    cell_set = set(map(str, known_cells))
    pset = set(map(str, program_names))

    score_cell_by_program = (
        len(set(usages.index).intersection(cell_set))
        + len(set(usages.columns).intersection(pset))
    )
    score_program_by_cell = (
        len(set(usages.columns).intersection(cell_set))
        + len(set(usages.index).intersection(pset))
    )

    if score_program_by_cell > score_cell_by_program:
        usages = usages.T

    usages.index = usages.index.astype(str)
    usages.columns = usages.columns.astype(str)
    usages = usages.apply(pd.to_numeric, errors="coerce").fillna(0.0)
    return usages


def choose_analysis_cells(
    metadata: pd.DataFrame,
    mask_program_names: Sequence[str],
) -> Tuple[pd.Index, pd.DataFrame, pd.DataFrame, bool]:
    rna_cells = read_names(ensure_exists(CONFIG["rna_cells_file"], "RNA cells file"))
    meta_cells = pd.Index(metadata.index.astype(str))

    base = rna_cells.intersection(meta_cells)
    if len(base) == 0:
        raise ValueError("No RNA cells overlap the selected metadata cells.")

    paired_atac = False
    if bool(CONFIG["prefer_common_rna_atac_cells"]):
        atac_cells_path = Path(CONFIG["atac_cells_file"])
        if atac_cells_path.exists():
            atac_cells = read_names(atac_cells_path)
            common = base.intersection(atac_cells)
            if len(common) > 0:
                base = common
                paired_atac = True
                print(f"[CELL] using common RNA/ATAC cells: {len(base)}")
            else:
                print("[WARN] No common RNA/ATAC barcodes. Primary FCI will remain RNA-only.")
        else:
            print("[WARN] ATAC cells file absent. Primary FCI will remain RNA-only.")

    usages = read_table_auto(ensure_exists(CONFIG["usages_file"], "cNMF usages file"))
    usages = orient_usages_cell_by_program(usages, rna_cells, mask_program_names)

    with_usage = base.intersection(usages.index)
    if len(with_usage) == 0:
        raise ValueError("No selected RNA cells overlap cNMF usages.")

    if len(with_usage) < len(base):
        warnings.warn(
            f"{len(base) - len(with_usage)} selected cells are absent from cNMF usages "
            "and will be excluded."
        )

    selected = with_usage
    meta_sel = metadata.loc[selected].copy()
    usages_sel = usages.loc[selected].copy()

    return selected, meta_sel, usages_sel, paired_atac


