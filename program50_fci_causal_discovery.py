def load_fixed_program_genes(
    mask_file: str | Path,
    target_program: object,
    expected_n: int = 50,
) -> Tuple[str, List[str], pd.DataFrame]:
    mask = read_table_auto(mask_file)
    mask = mask.apply(pd.to_numeric, errors="coerce").fillna(0.0)

    program = resolve_program_name(target_program, list(mask.index))
    row = mask.loc[program]

    if isinstance(row, pd.DataFrame):
        if len(row) != 1:
            raise ValueError(f"Program {program!r} appears multiple times in mask.")
        row = row.iloc[0]

    genes = [str(g) for g, v in row.items() if float(v) > 0]

    if len(genes) != expected_n:
        raise ValueError(
            f"{program} must contain exactly {expected_n} canonical genes, "
            f"but mask contains {len(genes)}."
        )

    if len(set(genes)) != expected_n:
        raise ValueError("Duplicate genes found in canonical program mask.")

    return program, genes, mask


