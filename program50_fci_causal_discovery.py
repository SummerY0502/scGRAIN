# Rank-based inverse normal transform
# =============================================================================

def inverse_normal_transform_df(df: pd.DataFrame) -> pd.DataFrame:
    n = len(df)
    out = np.zeros(df.shape, dtype=np.float64)

    for j, c in enumerate(df.columns):
        x = df[c].to_numpy(dtype=float)
        if not np.isfinite(x).all():
            raise ValueError(f"Non-finite values in gene {c} before rank transform.")

        if np.nanstd(x) <= 1e-12:
            raise ValueError(
                f"Gene {c} is constant across pseudo-metacells. "
                "FCI cannot keep all fixed 50 variables under this data state."
            )

        r = rankdata(x, method="average")
        p = (r - 0.5) / float(n)
        eps = 0.5 / float(n)
        p = np.clip(p, eps, 1.0 - eps)
        out[:, j] = norm.ppf(p)

    return pd.DataFrame(out, index=df.index, columns=df.columns)


