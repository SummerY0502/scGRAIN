RELATION_TYPES = ["-->", "<--", "<->", "o->", "<-o", "o-o", "---", "--o", "o--"]
ENDPOINT_TYPES = ["TAIL", "ARROW", "CIRCLE"]


def run_subsample_stability(
    X: pd.DataFrame,
    outdir: Path,
    primary_edges: pd.DataFrame,
) -> pd.DataFrame:
    stability_dir = outdir / "subsample_runs"
    stability_dir.mkdir(parents=True, exist_ok=True)

    B = int(CONFIG["n_subsamples"])
    frac = float(CONFIG["subsample_fraction"])
    alpha = float(CONFIG["primary_alpha"])
    seed = int(CONFIG["seed"])

    n = len(X)
    m = max(X.shape[1] + 4, int(round(frac * n)))
    if m >= n:
        m = n - 1
    if m <= X.shape[1] + 3:
        raise ValueError(
            f"Subsample size {m} is too small for {X.shape[1]} variables. "
            "Increase the number of pseudo-metacells or subsample_fraction."
        )

    genes = list(X.columns.astype(str))
    rng = np.random.default_rng(seed)

    # Deterministically pre-generate every subset so reruns are reproducible.
    subsets = [
        np.sort(rng.choice(n, size=m, replace=False))
        for _ in range(B)
    ]

    for b, idx in enumerate(subsets, start=1):
        path = stability_dir / f"subsample_{b:04d}.csv"
        if path.exists():
            print(f"[STABILITY] reuse {b}/{B}")
            continue

        print(f"[STABILITY] run {b}/{B}, n={m}, alpha={alpha:g}")
        _, ed = run_fci(X.iloc[idx], alpha=alpha)
        ed.insert(0, "subsample_id", b)
        ed.insert(1, "n_samples", m)
        ed.to_csv(path, index=False)

    # Aggregate.
    pair_stats: Dict[Tuple[str, str], dict] = {}
    for i, a in enumerate(genes):
        for b in genes[i + 1:]:
            pair_stats[(a, b)] = {
                "adjacency_count": 0,
                "relation_counts": Counter(),
                "endpoint_a_counts": Counter(),
                "endpoint_b_counts": Counter(),
            }

    used_runs = 0
    for b in range(1, B + 1):
        path = stability_dir / f"subsample_{b:04d}.csv"
        if not path.exists():
            continue
        ed = pd.read_csv(path)
        used_runs += 1

        for r in ed.itertuples(index=False):
            key = (str(r.gene_a), str(r.gene_b))
            if key not in pair_stats:
                raise KeyError(f"Unexpected pair in stability result: {key}")

            s = pair_stats[key]
            s["adjacency_count"] += 1
            s["relation_counts"][str(r.relation_a_to_b)] += 1
            s["endpoint_a_counts"][str(r.endpoint_a)] += 1
            s["endpoint_b_counts"][str(r.endpoint_b)] += 1

    if used_runs != B:
        raise RuntimeError(f"Expected {B} stability runs, found {used_runs}.")

    primary_map = {
        (str(r.gene_a), str(r.gene_b)): str(r.relation_a_to_b)
        for r in primary_edges.itertuples(index=False)
    }

    rows = []
    for (a, b), s in pair_stats.items():
        rec = {
            "gene_a": a,
            "gene_b": b,
            "n_subsamples": B,
            "adjacency_count": s["adjacency_count"],
            "adjacency_stability": s["adjacency_count"] / B,
            "primary_relation": primary_map.get((a, b), ""),
            "primary_adjacent": (a, b) in primary_map,
        }

        for rel in RELATION_TYPES:
            rec[f"relation_{rel}_stability"] = s["relation_counts"][rel] / B

        for ep in ENDPOINT_TYPES:
            rec[f"endpoint_a_{ep}_stability"] = s["endpoint_a_counts"][ep] / B
            rec[f"endpoint_b_{ep}_stability"] = s["endpoint_b_counts"][ep] / B

        pr = rec["primary_relation"]
        if pr:
            rec["exact_primary_relation_stability"] = s["relation_counts"][pr] / B
        else:
            rec["exact_primary_relation_stability"] = np.nan

        rows.append(rec)

    out = pd.DataFrame(rows)
    out = out.sort_values(
        ["primary_adjacent", "adjacency_stability"],
        ascending=[False, False],
    ).reset_index(drop=True)

    out.to_csv(outdir / "09_subsample_stability_all_pairs.csv", index=False)

    primary_out = out[out["primary_adjacent"]].copy()
    primary_out.to_csv(
        outdir / "10_primary_fci_edges_with_stability.csv",
        index=False,
    )

    return out


