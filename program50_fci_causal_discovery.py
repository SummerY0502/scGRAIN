def load_causallearn():
    try:
        from causallearn.search.ConstraintBased.FCI import fci
        from causallearn.search.ConstraintBased.PC import pc
        from causallearn.utils.cit import fisherz
        return fci, pc, fisherz
    except Exception as e:
        raise RuntimeError(
            "causal-learn is required for FCI/PC-stable.\n"
            "Install in the SAME Python environment with:\n"
            "    pip install causal-learn\n"
            f"Original import error: {e}"
        ) from e


def _endpoint_name(endpoint) -> str:
    if hasattr(endpoint, "name"):
        return str(endpoint.name).upper()
    s = str(endpoint).upper()
    for k in ["TAIL", "ARROW", "CIRCLE", "NULL", "STAR"]:
        if k in s:
            return k
    return s


def relation_from_endpoints(ep_a: str, ep_b: str) -> str:
    mapping = {
        ("TAIL", "ARROW"): "-->",
        ("ARROW", "TAIL"): "<--",
        ("ARROW", "ARROW"): "<->",
        ("CIRCLE", "ARROW"): "o->",
        ("ARROW", "CIRCLE"): "<-o",
        ("CIRCLE", "CIRCLE"): "o-o",
        ("TAIL", "TAIL"): "---",
        ("TAIL", "CIRCLE"): "--o",
        ("CIRCLE", "TAIL"): "o--",
    }
    return mapping.get((ep_a, ep_b), f"{ep_a}-{ep_b}")


def edge_properties_text(edge) -> str:
    props = getattr(edge, "properties", None)
    if props is None:
        return ""
    vals = []
    for p in props:
        if hasattr(p, "name"):
            vals.append(str(p.name))
        else:
            vals.append(str(p))
    return ";".join(sorted(set(vals)))


def _resolve_causallearn_node_name(
    raw_name: str,
    gene_order: Sequence[str],
) -> str:

    raw_name = str(raw_name)
    genes = [str(g) for g in gene_order]

    # Newer versions / algorithms that preserve the user-provided names.
    if raw_name in set(genes):
        return raw_name

    # Older FCI versions use 1-based generic labels X1..Xp.
    m = re.fullmatch(r"X(\d+)", raw_name, flags=re.IGNORECASE)
    if m is not None:
        idx = int(m.group(1)) - 1
        if 0 <= idx < len(genes):
            return genes[idx]

    raise KeyError(
        f"Cannot map causal-learn node {raw_name!r} to one of the "
        f"{len(genes)} fixed program genes. Expected an exact gene name or "
        "a generic X1..Xp node label."
    )


def graph_to_edge_dataframe(
    graph,
    gene_order: Sequence[str],
) -> pd.DataFrame:
    genes = [str(g) for g in gene_order]
    pos = {g: i for i, g in enumerate(genes)}
    rows = []

    for edge in graph.get_graph_edges():
        raw_n1 = str(edge.get_node1().get_name())
        raw_n2 = str(edge.get_node2().get_name())
        n1 = _resolve_causallearn_node_name(raw_n1, genes)
        n2 = _resolve_causallearn_node_name(raw_n2, genes)
        ep1 = _endpoint_name(edge.get_endpoint1())
        ep2 = _endpoint_name(edge.get_endpoint2())

        # Canonical pair order follows the fixed-50 gene order.
        if pos[n1] <= pos[n2]:
            a, b = n1, n2
            raw_a, raw_b = raw_n1, raw_n2
            epa, epb = ep1, ep2
        else:
            a, b = n2, n1
            raw_a, raw_b = raw_n2, raw_n1
            epa, epb = ep2, ep1

        rows.append({
            "gene_a": a,
            "gene_b": b,
            "causallearn_node_a": raw_a,
            "causallearn_node_b": raw_b,
            "endpoint_a": epa,
            "endpoint_b": epb,
            "relation_a_to_b": relation_from_endpoints(epa, epb),
            "edge_properties": edge_properties_text(edge),
        })

    if not rows:
        return pd.DataFrame(
            columns=[
                "gene_a", "gene_b",
                "causallearn_node_a", "causallearn_node_b",
                "endpoint_a", "endpoint_b",
                "relation_a_to_b", "edge_properties",
            ]
        )

    out = pd.DataFrame(rows)
    out["__ia"] = out["gene_a"].map(pos)
    out["__ib"] = out["gene_b"].map(pos)
    out = out.sort_values(["__ia", "__ib"]).drop(columns=["__ia", "__ib"])
    return out.reset_index(drop=True)


def run_fci(
    X: pd.DataFrame,
    alpha: float,
) -> Tuple[object, pd.DataFrame]:
    fci, _, fisherz = load_causallearn()

    kwargs = {
        "dataset": X.to_numpy(dtype=np.float64),
        "independence_test_method": fisherz,
        "alpha": float(alpha),
        "depth": int(CONFIG["fci_depth"]),
        "max_path_length": int(CONFIG["fci_max_path_length"]),
        "verbose": False,
        "show_progress": False,
        "node_names": list(X.columns.astype(str)),
    }

    # Compatibility with causal-learn versions. Some older FCI versions accept
    # **kwargs but silently ignore node_names and return X1..Xp. Do not rely on
    # **kwargs for node_names; the exporter below maps X1..Xp back to columns.
    sig = inspect.signature(fci)
    explicit = set(sig.parameters)
    has_var_kwargs = any(
        p.kind == inspect.Parameter.VAR_KEYWORD
        for p in sig.parameters.values()
    )
    filtered = {}
    for k, v in kwargs.items():
        if k == "node_names":
            if k in explicit:
                filtered[k] = v
        elif k in explicit or has_var_kwargs:
            filtered[k] = v
    kwargs = filtered

    graph, _colored_edges = fci(**kwargs)
    edge_df = graph_to_edge_dataframe(graph, list(X.columns.astype(str)))
    return graph, edge_df


def run_pc_stable(
    X: pd.DataFrame,
    alpha: float,
) -> pd.DataFrame:
    _, pc, fisherz = load_causallearn()

    kwargs = {
        "data": X.to_numpy(dtype=np.float64),
        "alpha": float(alpha),
        "indep_test": fisherz,
        "stable": True,
        "verbose": False,
        "show_progress": False,
        "node_names": list(X.columns.astype(str)),
    }

    sig = inspect.signature(pc)
    kwargs = {k: v for k, v in kwargs.items() if k in sig.parameters}

    cg = pc(**kwargs)
    return graph_to_edge_dataframe(cg.G, list(X.columns.astype(str)))


