def prepare_usage_embedding(
    usages_sel: pd.DataFrame,
    target_program: str,
    known_program_names: Sequence[str],
) -> Tuple[np.ndarray, List[str]]:
    usage_program = resolve_program_name(target_program, list(usages_sel.columns))
    Xdf = usages_sel.drop(columns=[usage_program]).copy()

    # Drop constant usage dimensions.
    std = Xdf.std(axis=0, ddof=0)
    Xdf = Xdf.loc[:, std > 1e-12]

    if Xdf.shape[1] == 0:
        raise ValueError("No non-constant cNMF usage dimensions remain after excluding target program.")

    # cNMF usage is nonnegative in normal outputs; log1p reduces extreme leverage.
    X = np.log1p(np.maximum(Xdf.to_numpy(dtype=float), 0.0))
    X = StandardScaler(with_mean=True, with_std=True).fit_transform(X)

    max_dim = int(CONFIG["metacell_pca_dim"])
    ncomp = min(max_dim, X.shape[1], X.shape[0] - 1)
    if ncomp >= 2 and X.shape[1] > ncomp:
        X = PCA(n_components=ncomp, random_state=int(CONFIG["seed"])).fit_transform(X)

    return np.asarray(X, dtype=np.float64), list(Xdf.columns.astype(str))


def _merge_small_clusters(
    Z: np.ndarray,
    labels: np.ndarray,
    min_size: int,
) -> np.ndarray:
    labels = np.asarray(labels, dtype=int).copy()

    while True:
        uniq, counts = np.unique(labels, return_counts=True)
        small = uniq[counts < min_size]
        if len(small) == 0 or len(uniq) <= 1:
            break

        centers = {
            int(k): Z[labels == k].mean(axis=0)
            for k in uniq
        }

        changed = False
        for k in list(small):
            idx = np.where(labels == k)[0]
            if len(idx) == 0:
                continue

            candidates = [int(j) for j in np.unique(labels) if int(j) != int(k)]
            if not candidates:
                continue

            c0 = centers[int(k)]
            distances = [
                float(np.sum((c0 - centers[j]) ** 2))
                for j in candidates
            ]
            nearest = candidates[int(np.argmin(distances))]
            labels[idx] = nearest
            changed = True

        if not changed:
            break

    # Relabel 0..K-1
    uniq = list(np.unique(labels))
    remap = {old: new for new, old in enumerate(uniq)}
    return np.array([remap[int(x)] for x in labels], dtype=int)


def cluster_one_stratum(
    Z: np.ndarray,
    seed: int,
    target_size: int,
    min_size: int,
) -> np.ndarray:
    n = Z.shape[0]
    if n <= target_size:
        return np.zeros(n, dtype=int)

    # Do not ask for more clusters than can possibly satisfy min_size.
    k_target = max(1, int(round(n / float(target_size))))
    k_max_by_min = max(1, n // max(1, min_size))
    k = min(k_target, k_max_by_min)

    if k <= 1:
        return np.zeros(n, dtype=int)

    km = MiniBatchKMeans(
        n_clusters=k,
        random_state=seed,
        n_init=20,
        batch_size=min(max(256, 8 * k), max(256, n)),
        max_iter=500,
    )
    labels = km.fit_predict(Z)
    labels = _merge_small_clusters(Z, labels, min_size=min_size)
    return labels


def build_pseudometacells(
    selected_cells: pd.Index,
    metadata_sel: pd.DataFrame,
    usages_sel: pd.DataFrame,
    target_program: str,
    all_program_names: Sequence[str],
) -> Tuple[pd.Series, pd.DataFrame, np.ndarray, List[str]]:
    Z, embedding_features = prepare_usage_embedding(
        usages_sel, target_program, all_program_names
    )

    strat_cols = [str(x) for x in CONFIG["metacell_stratify_columns"]]
    for c in strat_cols:
        if c not in metadata_sel.columns:
            raise KeyError(
                f"metacell_stratify_columns contains {c!r}, but metadata does not."
            )

    if strat_cols:
        strata = metadata_sel[strat_cols].astype(str).agg("||".join, axis=1)
    else:
        strata = pd.Series("__ALL__", index=selected_cells)

    labels = np.full(len(selected_cells), -1, dtype=int)
    global_offset = 0
    rng = np.random.default_rng(int(CONFIG["seed"]))

    for stratum in pd.unique(strata):
        idx = np.where(strata.to_numpy() == stratum)[0]
        local_Z = Z[idx]

        local_labels = cluster_one_stratum(
            local_Z,
            seed=int(rng.integers(0, 2**31 - 1)),
            target_size=int(CONFIG["target_cells_per_metacell"]),
            min_size=int(CONFIG["min_cells_per_metacell"]),
        )

        labels[idx] = local_labels + global_offset
        global_offset += int(local_labels.max()) + 1

    if (labels < 0).any():
        raise RuntimeError("Internal error: unassigned pseudo-metacell labels.")

    # Make IDs stable and readable.
    uniq = sorted(np.unique(labels))
    relabel = {old: new for new, old in enumerate(uniq)}
    labels = np.array([relabel[int(x)] for x in labels], dtype=int)

    label_series = pd.Series(
        labels,
        index=selected_cells,
        name="metacell_id",
        dtype=int,
    )

    records = []
    for mid, cell_idx in label_series.groupby(label_series).groups.items():
        cells = list(cell_idx)
        rec = {
            "metacell_id": int(mid),
            "n_cells": len(cells),
        }
        for c in strat_cols:
            vals = metadata_sel.loc[cells, c].astype(str)
            rec[c] = vals.mode().iloc[0] if len(vals) else ""
        records.append(rec)

    meta_summary = pd.DataFrame(records).sort_values("metacell_id")

    return label_series, meta_summary, Z, embedding_features


# =============================================================================
# MatrixMarket streaming: read only the fixed 50 genes, but compute whole-library
# size for selected cells.
# =============================================================================

def get_mtx_shape_and_skiprows(matrix_file: str | Path) -> Tuple[int, int, int, int]:
    matrix_file = Path(matrix_file)
    with open(matrix_file, "rt") as f:
        first = f.readline().strip()
        if "matrix" not in first.lower() or "coordinate" not in first.lower():
            raise ValueError(f"{matrix_file}: not a coordinate MatrixMarket file.")

        skiprows = 1
        for line in f:
            skiprows += 1
            line = line.strip()
            if not line or line.startswith("%"):
                continue
            parts = line.split()
            if len(parts) < 3:
                raise ValueError(f"Cannot parse MatrixMarket size line: {line}")
            n_rows, n_cols, n_entries = map(int, parts[:3])
            return n_rows, n_cols, n_entries, skiprows

    raise ValueError(f"Cannot find MatrixMarket size line: {matrix_file}")


def stream_raw_target_counts(
    matrix_file: str | Path,
    all_cells: Sequence[str],
    all_features: Sequence[str],
    target_features: Sequence[str],
    selected_cells: Sequence[str],
    chunksize: int,
) -> Tuple[sparse.csr_matrix, np.ndarray]:
    """
    Return:
        target_counts: target_features x selected_cells raw-count CSR
        library_size: whole-library raw counts per selected cell
    """
    matrix_file = Path(matrix_file)
    all_cells = pd.Index(all_cells).astype(str)
    all_features = pd.Index(all_features).astype(str)
    selected_cells = pd.Index(selected_cells).astype(str)
    target_features = pd.Index(target_features).astype(str)

    selected_pos = all_cells.get_indexer(selected_cells)
    if (selected_pos < 0).any():
        missing = selected_cells[selected_pos < 0][:10].tolist()
        raise ValueError(f"Selected cells missing from matrix cell list: {missing}")

    target_pos = all_features.get_indexer(target_features)
    if (target_pos < 0).any():
        missing = target_features[target_pos < 0][:20].tolist()
        raise ValueError(f"Target program genes missing from matrix features: {missing}")

    n_rows, n_cols, n_entries, skiprows = get_mtx_shape_and_skiprows(matrix_file)

    if (n_rows, n_cols) == (len(all_features), len(all_cells)):
        orientation = "feature_by_cell"
    elif (n_rows, n_cols) == (len(all_cells), len(all_features)):
        orientation = "cell_by_feature"
    else:
        raise ValueError(
            f"{matrix_file}: shape {(n_rows, n_cols)} incompatible with "
            f"features={len(all_features)}, cells={len(all_cells)}"
        )

    cell_to_selected = np.full(len(all_cells), -1, dtype=np.int64)
    cell_to_selected[selected_pos] = np.arange(len(selected_cells), dtype=np.int64)

    feature_to_target = np.full(len(all_features), -1, dtype=np.int64)
    feature_to_target[target_pos] = np.arange(len(target_features), dtype=np.int64)

    lib = np.zeros(len(selected_cells), dtype=np.float64)
    out_rows, out_cols, out_vals = [], [], []

    print(f"[MTX] streaming {matrix_file}")
    print(f"      orientation={orientation}, entries={n_entries:,}")
    print(f"      selected cells={len(selected_cells)}, target genes={len(target_features)}")

    reader = pd.read_csv(
        matrix_file,
        sep=r"\s+",
        header=None,
        names=["i", "j", "x"],
        skiprows=skiprows,
        chunksize=int(chunksize),
        engine="c",
    )

    processed = 0
    for chunk in reader:
        i = chunk["i"].to_numpy(dtype=np.int64) - 1
        j = chunk["j"].to_numpy(dtype=np.int64) - 1
        x = chunk["x"].to_numpy(dtype=np.float64)

        if orientation == "feature_by_cell":
            feat_raw = i
            cell_raw = j
        else:
            cell_raw = i
            feat_raw = j

        cell_idx = cell_to_selected[cell_raw]
        keep_cell = cell_idx >= 0

        if keep_cell.any():
            cell_idx = cell_idx[keep_cell]
            feat_raw = feat_raw[keep_cell]
            x2 = x[keep_cell]

            lib += np.bincount(
                cell_idx,
                weights=x2,
                minlength=len(selected_cells),
            )

            target_idx = feature_to_target[feat_raw]
            keep_target = target_idx >= 0
            if keep_target.any():
                out_rows.append(target_idx[keep_target].astype(np.int32))
                out_cols.append(cell_idx[keep_target].astype(np.int32))
                out_vals.append(x2[keep_target].astype(np.float32))

        processed += len(chunk)
        if processed % (int(chunksize) * 10) == 0:
            print(f"      processed {processed:,}/{n_entries:,}")

    if len(out_vals) == 0:
        mat = sparse.csr_matrix(
            (len(target_features), len(selected_cells)),
            dtype=np.float32,
        )
    else:
        rows = np.concatenate(out_rows)
        cols = np.concatenate(out_cols)
        vals = np.concatenate(out_vals)
        mat = sparse.coo_matrix(
            (vals, (rows, cols)),
            shape=(len(target_features), len(selected_cells)),
            dtype=np.float32,
        ).tocsr()

    return mat, lib


