def build_metacell_covariates(
    metadata_sel: pd.DataFrame,
    metacell_labels: pd.Series,
    covariates: Sequence[str],
) -> pd.DataFrame:
    covariates = [str(x) for x in covariates]
    if not covariates:
        return pd.DataFrame(index=sorted(metacell_labels.unique()))

    for c in covariates:
        if c not in metadata_sel.columns:
            raise KeyError(f"technical_covariate {c!r} not found in metadata.")

    cell_df_parts = []

    for c in covariates:
        s = metadata_sel.loc[metacell_labels.index, c]

        numeric_s = pd.to_numeric(s, errors="coerce")
        frac_numeric = float(numeric_s.notna().mean())

        if frac_numeric >= 0.95:
            part = pd.DataFrame(
                {f"{c}__numeric": numeric_s.fillna(numeric_s.median()).astype(float)},
                index=s.index,
            )
        else:
            part = pd.get_dummies(
                s.astype(str),
                prefix=c,
                dtype=float,
                drop_first=True,
            )
            if part.shape[1] == 0:
                continue

        cell_df_parts.append(part)

    if not cell_df_parts:
        return pd.DataFrame(index=sorted(metacell_labels.unique()))

    cell_cov = pd.concat(cell_df_parts, axis=1)
    tmp = cell_cov.copy()
    tmp["__metacell_id__"] = metacell_labels.loc[tmp.index].to_numpy(dtype=int)

    meta_cov = tmp.groupby("__metacell_id__", sort=True).mean()
    meta_cov.index.name = "metacell_id"

    # Remove constant covariates.
    if meta_cov.shape[1] > 0:
        std = meta_cov.std(axis=0, ddof=0)
        meta_cov = meta_cov.loc[:, std > 1e-12]

    return meta_cov


def residualize_matrix(Y: pd.DataFrame, cov: pd.DataFrame) -> pd.DataFrame:
    if cov is None or cov.shape[1] == 0:
        return Y.copy()

    if not Y.index.equals(cov.index):
        cov = cov.reindex(Y.index)
    if cov.isna().any().any():
        raise ValueError("NaN in metacell technical covariates after alignment.")

    X = cov.to_numpy(dtype=float)
    X = StandardScaler(with_mean=True, with_std=True).fit_transform(X)
    X = np.column_stack([np.ones(X.shape[0]), X])

    YY = Y.to_numpy(dtype=float)
    beta, *_ = np.linalg.lstsq(X, YY, rcond=None)
    resid = YY - X @ beta

    return pd.DataFrame(resid, index=Y.index, columns=Y.columns)


