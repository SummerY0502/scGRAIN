def build_gene_qc(
    fixed_genes: Sequence[str],
    cell_counts: sparse.csr_matrix,
    meta_raw: pd.DataFrame,
    meta_log: pd.DataFrame,
    causal_input: pd.DataFrame,
) -> pd.DataFrame:
    n_cells = cell_counts.shape[1]
    cell_detection = np.asarray((cell_counts > 0).sum(axis=1)).reshape(-1) / max(1, n_cells)

    meta_detection = (meta_raw.to_numpy(dtype=float) > 0).mean(axis=0)

    rows = []
    for j, g in enumerate(fixed_genes):
        rows.append({
            "gene": str(g),
            "cell_detection_fraction": float(cell_detection[j]),
            "metacell_detection_fraction": float(meta_detection[j]),
            "metacell_log1p_mean": float(meta_log.iloc[:, j].mean()),
            "metacell_log1p_std": float(meta_log.iloc[:, j].std(ddof=0)),
            "causal_input_mean": float(causal_input.iloc[:, j].mean()),
            "causal_input_std": float(causal_input.iloc[:, j].std(ddof=0)),
        })

    return pd.DataFrame(rows)


