def alpha_tag(alpha: float) -> str:
    return (f"{alpha:.6g}").replace(".", "p").replace("-", "m")


def run_alpha_sensitivity(
    X: pd.DataFrame,
    outdir: Path,
) -> Tuple[Dict[float, pd.DataFrame], pd.DataFrame]:
    alpha_dir = outdir / "alpha_sensitivity"
    alpha_dir.mkdir(parents=True, exist_ok=True)

    results: Dict[float, pd.DataFrame] = {}
    genes = list(X.columns.astype(str))
    all_pairs = [(genes[i], genes[j]) for i in range(len(genes)) for j in range(i + 1, len(genes))]

    for alpha in [float(x) for x in CONFIG["alpha_grid"]]:
        path = alpha_dir / f"fci_alpha_{alpha_tag(alpha)}_edges.csv"

        if path.exists():
            print(f"[ALPHA] reuse {path.name}")
            ed = pd.read_csv(path)
        else:
            print(f"[ALPHA] FCI alpha={alpha:g}")
            _, ed = run_fci(X, alpha=alpha)
            ed.insert(0, "alpha", alpha)
            ed.to_csv(path, index=False)

        results[alpha] = ed

    # Pair-level sensitivity table over all 1225 pairs.
    rows = []
    for a, b in all_pairs:
        rels = []
        endpoints_a = []
        endpoints_b = []
        present_alphas = []

        for alpha, ed in results.items():
            hit = ed[(ed["gene_a"].astype(str) == a) & (ed["gene_b"].astype(str) == b)]
            if len(hit):
                r = hit.iloc[0]
                rels.append(str(r["relation_a_to_b"]))
                endpoints_a.append(str(r["endpoint_a"]))
                endpoints_b.append(str(r["endpoint_b"]))
                present_alphas.append(alpha)

        rows.append({
            "gene_a": a,
            "gene_b": b,
            "n_alpha_values": len(results),
            "n_alpha_adjacent": len(present_alphas),
            "adjacency_fraction_across_alpha_grid": (
                len(present_alphas) / max(1, len(results))
            ),
            "alphas_adjacent": ";".join(f"{x:g}" for x in present_alphas),
            "relations_when_adjacent": ";".join(rels),
            "endpoint_a_when_adjacent": ";".join(endpoints_a),
            "endpoint_b_when_adjacent": ";".join(endpoints_b),
        })

    sensitivity = pd.DataFrame(rows)
    sensitivity.to_csv(
        outdir / "07_alpha_sensitivity_all_pairs.csv",
        index=False,
    )

    return results, sensitivity


